import { fileURLToPath } from "node:url";
import type { PgDatabase, PgQueryResultHKT } from "drizzle-orm/pg-core";
import type * as schema from "./schema.js";

/**
 * The database every repository works with: the built-in database (PGlite, Postgres
 * compiled to WebAssembly), a real Postgres server, or MySQL or MariaDB. Repositories are
 * written once against the Postgres type and never know which one they are talking to; see
 * src/database/dialect/README.md for how MySQL fits behind it.
 */
export type Database = PgDatabase<PgQueryResultHKT, typeof schema>;

/** The handle a `database.transaction(async (transaction) => ...)` callback receives. */
export type Transaction = Parameters<Parameters<Database["transaction"]>[0]>[0];

/**
 * Repositories accept either, so a service can run several of them inside one transaction
 * and have them all succeed or fail together.
 */
export type DatabaseOrTransaction = Database | Transaction;

/**
 * "built-in" is PGlite, stored in .lintel/data; "postgres" is a server someone runs, and
 * "mysql" is a MySQL or MariaDB server.
 */
export type DatabaseKind = "built-in" | "postgres" | "mysql";

/** An open database, with what it takes to bring its tables up to date and to close it. */
export interface OpenedDatabase {
  database: Database;
  kind: DatabaseKind;
  /** Creates or updates the tables. Safe to run every time: applied steps are skipped. */
  applyMigrations: () => Promise<void>;
  /** The same for plugins' own tables, each recorded apart (see `pluginMigrationsTable`). */
  applyPluginMigrations: (plugins: readonly PluginMigrations[]) => Promise<void>;
  close: () => Promise<void>;
}

/** Where a plugin's migrations are, from its `database.migrationsFolder`. */
export interface PluginMigrations {
  pluginId: string;
  migrationsFolder: string;
  /** Its migrations for MySQL and MariaDB, if it has any. */
  mysqlMigrationsFolder?: string;
}

/**
 * Drizzle records applied migrations in a table, and decides what to run by comparing it
 * with a folder. Each plugin gets its own record, next to Lintel's in the "drizzle" schema,
 * so plugins' migrations and Lintel's never mistake each other for their own.
 */
export function pluginMigrationsTable(pluginId: string): string {
  return `__plugin_${pluginId.replaceAll("-", "_")}_migrations`;
}

/** Generated by `pnpm db:generate`; the same folder from `src` (tsx) and from `dist`. */
export const MIGRATIONS_FOLDER = fileURLToPath(new URL("../../migrations", import.meta.url));
