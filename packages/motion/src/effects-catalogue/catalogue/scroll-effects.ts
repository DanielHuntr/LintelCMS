const reveal = (id: string, name: string, description: string, shape: string) =>
  defineEffect({
    id,
    name,
    description,
    category: "scroll",
    kind: "behaviour",
    module: "scroll",
    behaviour: "revealMask",
    suits: ["image", "container"],
    params: { end: number("Fully shown by", 0.5, 0.2, 0.9, { step: 0.05 }) },
    fixed: { shape },
    reducedMotion: "Shows the whole thing.",
    preview: "image",
    keywords: ["mask", "reveal", "clip"],
  });

