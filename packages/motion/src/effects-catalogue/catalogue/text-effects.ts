/**
 * Effects for words. The text is always in the page, so it reads without scripts and
 * screen readers hear it once, whole.
 */

const trigger = choice("When it plays", "view", [
  ["view", "When it scrolls into view"],
  ["hover", "When the pointer is over it"],
]);
const letters = (start: Record<string, number | string>, delay = 30) => ({
  trigger: { type: "inView" as const, threshold: 0.3 },
  targets: { type: "text" as const, split: "letters" as const },
  stagger: { each: delay, from: "first" as const },
  duration: 600,
  easing: "easeOutCubic" as const,
  tracks: Object.entries(start).map(([property, value]) =>
    fromTo(
      property as never,
      value,
      property === "opacity" ? 1 : property.startsWith("scale") ? 1 : 0,
    ),
  ),
});

